/**
 * Build step for SafeFileDrag.
 *
 * Produces a loadable (temporary) add-on in `dist/`:
 *   dist/manifest.json   copied verbatim from the repository root
 *   dist/content.js      the bundled content script (IIFE, no modules at runtime)
 *
 * The bundle is intentionally not minified: this extension is small, security
 * sensitive and meant to be read by whoever installs or reviews it.
 */
import { build } from 'esbuild';
import { mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

await build({
  entryPoints: [join(root, 'src', 'content.ts')],
  outfile: join(dist, 'content.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  // Firefox 128 is the first release with `world: "MAIN"` content scripts.
  target: ['firefox128'],
  minify: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: {
    js: [
      '/* SafeFileDrag — generated by scripts/build.mjs. Do not edit dist/ by hand. */',
      '/* Source: https://github.com/ (see README.md). No remote code, no eval. */',
    ].join('\n'),
  },
});

const manifest = JSON.parse(await readFile(join(root, 'manifest.json'), 'utf8'));
await writeFile(join(dist, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

console.log(`built ${manifest.name} ${manifest.version} -> dist/`);
