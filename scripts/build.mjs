/**
 * Build step for SafeFileDrag.
 *
 * Produces a loadable (temporary) add-on in `dist/`:
 *   dist/manifest.json   copied verbatim from the repository root
 *   dist/content.js      the bundled content script (IIFE, no modules at runtime)
 *   dist/icon/*.png      the add-on icons the manifest names
 *   dist/LICENSE         the licence text, shipped with the add-on
 *
 * The bundle is intentionally not minified: this extension is small, security
 * sensitive and meant to be read by whoever installs or reviews it.
 *
 * The build ends by checking the package against its own manifest: every file the
 * manifest names must exist in `dist/`. Signing the repository root instead of `dist/`
 * is the classic way to get `MANIFEST_CONTENT_SCRIPT_FILE_NOT_FOUND` from AMO, and this
 * check turns any such mismatch into a build failure that names the file.
 */
import { build } from 'esbuild';
import { copyFile, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { verifyPackage } from './lib/package-check.mjs';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'dist');

await rm(dist, { recursive: true, force: true });
await mkdir(dist, { recursive: true });

await build({
  entryPoints: [join(root, 'src', 'content.ts')],
  outfile: join(dist, 'content.js'),
  bundle: true,
  format: 'iife',
  platform: 'browser',
  // Firefox 128 is the first release with `world: "MAIN"` content scripts.
  target: ['firefox128'],
  minify: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: {
    js: [
      '/* SafeFileDrag — generated by scripts/build.mjs. Do not edit dist/ by hand. */',
      '/* Source: https://github.com/QZLin/SafeFileDrag — GPL-3.0-or-later. No remote code, no eval. */',
    ].join('\n'),
  },
});

const manifest = JSON.parse(await readFile(join(root, 'manifest.json'), 'utf8'));
await writeFile(join(dist, 'manifest.json'), `${JSON.stringify(manifest, null, 2)}\n`, 'utf8');

// Ship exactly the icons the manifest names. The SVG source and the resize script stay
// out of the package; `icon/` is a build input, the copied PNGs are the artifact.
for (const iconPath of new Set(Object.values(manifest.icons ?? {}))) {
  const destination = join(dist, iconPath);
  await mkdir(dirname(destination), { recursive: true });
  await copyFile(join(root, iconPath), destination);
}

// The licence travels with the package: this is the text a user of the signed .xpi gets.
await copyFile(join(root, 'LICENSE'), join(dist, 'LICENSE'));

const { problems } = await verifyPackage({
  distDir: dist,
  manifestPath: join(dist, 'manifest.json'),
});
if (problems.length > 0) {
  console.error('the built package does not match its manifest:');
  for (const problem of problems) console.error(`  - ${problem}`);
  console.error('sign and lint the built directory: --source-dir dist');
  process.exit(1);
}

console.log(`built ${manifest.name} ${manifest.version} -> dist/ (package checked)`);
